"""Professional PDF Exporter using fpdf2.

Transforms Markdown research reports into publication-grade, styled PDF documents
with corporate headers, page numbering, styled headings, bullet points, and tables.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import List, Optional

from fpdf import FPDF

logger = logging.getLogger("research_assistant.pdf")


class ResearchReportPDF(FPDF):
    """Custom FPDF subclass with corporate headers and footers."""

    def __init__(self, topic: str, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.topic = topic
        self.set_auto_page_break(auto=True, margin=18)

    def header(self):
        # Top banner on pages after page 1
        if self.page_no() > 1:
            self.set_font("helvetica", "I", 8)
            self.set_text_color(110, 115, 130)
            self.cell(
                0,
                8,
                f"Multi-Agent Research Report: {self.topic[:60]}...",
                border=0,
                align="L",
            )
            self.set_draw_color(220, 224, 230)
            self.line(10, 18, 200, 18)
            self.ln(6)

    def footer(self):
        self.set_y(-14)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(128, 132, 145)
        self.set_draw_color(220, 224, 230)
        self.line(10, 283, 200, 283)

        # Left footer: branding
        self.cell(0, 10, "Generated by Multi-Agent Research Assistant (CrewAI + Gemini)", align="L")
        # Right footer: page numbers
        self.set_x(-35)
        self.cell(0, 10, f"Page {self.page_no()}", align="R")


def clean_text_for_pdf(text: str) -> str:
    """Sanitize unicode characters for standard PDF Helvetica font compatibility."""
    replacements = {
        "“": '"',
        "”": '"',
        "‘": "'",
        "’": "'",
        "—": "-",
        "–": "-",
        "…": "...",
        "•": "*",
        "→": "->",
        "←": "<-",
        "≥": ">=",
        "≤": "<=",
        "±": "+/-",
        "™": "(TM)",
        "®": "(R)",
        "©": "(c)",
    }
    for char, rep in replacements.items():
        text = text.replace(char, rep)
    # Filter characters not representable in latin-1 if using core fonts
    return text.encode("latin-1", "replace").decode("latin-1")


def export_markdown_to_pdf(
    markdown_content: str,
    output_pdf_path: str | Path,
    topic: str = "Research Report",
) -> Path:
    """Convert Markdown research report content into a beautifully styled PDF document.

    Args:
        markdown_content: Raw Markdown string.
        output_pdf_path: Destination path for the generated PDF.
        topic: Research topic title for header/metadata.

    Returns:
        Path: Path to the generated PDF.
    """
    out_path = Path(output_pdf_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    pdf = ResearchReportPDF(topic=clean_text_for_pdf(topic), orientation="P", unit="mm", format="A4")
    pdf.set_margins(left=14, top=16, right=14)
    pdf.add_page()

    # Title block on page 1
    pdf.set_fill_color(24, 43, 73)  # Deep Navy Blue
    pdf.rect(14, 16, 182, 3, "F")
    pdf.set_y(22)

    lines = markdown_content.splitlines()
    in_code_block = False
    in_table = False
    table_rows: List[List[str]] = []

    def flush_table(rows: List[List[str]]):
        if not rows:
            return
        num_cols = max(len(r) for r in rows)
        if num_cols == 0:
            return
        # Calculate cell widths
        available_width = 182.0
        col_width = available_width / num_cols

        pdf.set_font("helvetica", "B", 8)
        pdf.set_fill_color(235, 240, 248)
        pdf.set_text_color(24, 43, 73)

        # Header row
        for header_cell in rows[0]:
            pdf.cell(col_width, 7, clean_text_for_pdf(header_cell.strip()[:35]), border=1, fill=True, align="C")
        pdf.ln()

        # Data rows
        pdf.set_font("helvetica", "", 8)
        pdf.set_text_color(40, 44, 52)
        for row in rows[1:]:
            for idx in range(num_cols):
                val = row[idx].strip() if idx < len(row) else ""
                pdf.cell(col_width, 6, clean_text_for_pdf(val[:40]), border=1, align="L")
            pdf.ln()
        pdf.ln(3)

    for line in lines:
        stripped = line.strip()

        # Handle Code blocks
        if stripped.startswith("```"):
            in_code_block = not in_code_block
            continue

        if in_code_block:
            pdf.set_font("courier", "", 8)
            pdf.set_text_color(60, 65, 75)
            pdf.cell(0, 5, clean_text_for_pdf(line[:110]), ln=True)
            continue

        # Handle Markdown Tables
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [c for c in stripped.split("|")[1:-1]]
            # Skip delimiter rows (e.g., |:---|:---|)
            if all(re.match(r"^[\s\-:]+$", c) for c in cells):
                continue
            table_rows.append(cells)
            in_table = True
            continue
        elif in_table:
            flush_table(table_rows)
            table_rows = []
            in_table = False

        # Blank line
        if not stripped:
            pdf.ln(2)
            continue

        # Level 1 Heading: # Title
        if stripped.startswith("# "):
            title_text = clean_text_for_pdf(stripped[2:])
            pdf.set_font("helvetica", "B", 18)
            pdf.set_text_color(18, 38, 70)  # Navy
            pdf.multi_cell(0, 9, title_text)
            pdf.set_draw_color(59, 130, 246)  # Accent blue underline
            pdf.line(14, pdf.get_y() + 1, 196, pdf.get_y() + 1)
            pdf.ln(4)
            continue

        # Level 2 Heading: ## Section
        if stripped.startswith("## "):
            sec_text = clean_text_for_pdf(stripped[3:])
            pdf.ln(3)
            pdf.set_font("helvetica", "B", 13)
            pdf.set_text_color(30, 58, 110)
            pdf.multi_cell(0, 7, sec_text)
            pdf.set_draw_color(209, 213, 219)
            pdf.line(14, pdf.get_y() + 1, 196, pdf.get_y() + 1)
            pdf.ln(2)
            continue

        # Level 3 Heading: ### Subsection
        if stripped.startswith("### "):
            sub_text = clean_text_for_pdf(stripped[4:])
            pdf.ln(2)
            pdf.set_font("helvetica", "B", 10.5)
            pdf.set_text_color(51, 65, 85)
            pdf.multi_cell(0, 6, sub_text)
            pdf.ln(1)
            continue

        # Blockquote: > Note
        if stripped.startswith("> "):
            quote_text = clean_text_for_pdf(stripped[2:])
            pdf.set_font("helvetica", "I", 9)
            pdf.set_text_color(71, 85, 105)
            pdf.set_fill_color(248, 250, 252)
            pdf.set_x(18)
            pdf.multi_cell(178, 5, quote_text, fill=True)
            pdf.ln(1)
            continue

        # Bullet point: - or *
        if stripped.startswith(("- ", "* ")):
            bullet_text = clean_text_for_pdf(stripped[2:])
            # Clean bold markers **
            bullet_text = bullet_text.replace("**", "")
            pdf.set_font("helvetica", "", 9.5)
            pdf.set_text_color(30, 41, 59)
            pdf.set_x(18)
            pdf.cell(4, 5, chr(149), ln=False)  # Bullet symbol
            pdf.multi_cell(174, 5, bullet_text)
            continue

        # Numbered list: 1. 2.
        if re.match(r"^\d+\.\s", stripped):
            match = re.match(r"^(\d+\.)\s*(.*)", stripped)
            if match:
                num_tag = match.group(1)
                body_text = clean_text_for_pdf(match.group(2).replace("**", ""))
                pdf.set_font("helvetica", "B", 9.5)
                pdf.set_text_color(30, 41, 59)
                pdf.set_x(18)
                pdf.cell(7, 5, num_tag, ln=False)
                pdf.set_font("helvetica", "", 9.5)
                pdf.multi_cell(171, 5, body_text)
                continue

        # Standard Paragraph text
        para_text = clean_text_for_pdf(stripped.replace("**", ""))
        pdf.set_font("helvetica", "", 9.5)
        pdf.set_text_color(30, 41, 59)
        pdf.multi_cell(0, 5, para_text)
        pdf.ln(1)

    # Flush any trailing table
    if in_table and table_rows:
        flush_table(table_rows)

    pdf.output(str(out_path))
    logger.info(f"Report exported successfully as PDF: {out_path}")
    return out_path
